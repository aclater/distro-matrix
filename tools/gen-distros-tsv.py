#!/usr/bin/env python3
"""Regenerate distros.tsv from the image-cache manifest (#23).

The manifest (default ~/.cache/pqc-vm-matrix/manifest.tsv) is the source of
truth for downloaded cloud images:

    alias  distro-dir  dated-filename  sha256  source-url

distros.tsv uses the same aliases, so an alias resolves either to the local
cache (<cache>/images/<alias>.qcow2) or to <image-root>/<distro-dir>/<dated-
filename> on the shared image store. Images that can't be downloaded
anonymously (RHEL) or aren't cached yet are listed in EXTRA below.

Usage:
    tools/gen-distros-tsv.py [--manifest PATH] [--output distros.tsv]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# alias prefix -> (family, os-release ID). Longest prefix wins.
IDS = {
    "rhel": ("rhel", "rhel"),
    "rocky": ("rhel", "rocky"),
    "alma": ("rhel", "almalinux"),
    "stream": ("rhel", "centos"),
    "fedora": ("rhel", "fedora"),
    "ol": ("rhel", "ol"),
    "al2023": ("rhel", "amzn"),
    "ubuntu": ("debian", "ubuntu"),
    "debian": ("debian", "debian"),
    "leap": ("suse", "opensuse-leap"),
    "tumbleweed": ("suse", "opensuse-tumbleweed"),
    "sles": ("suse", "sles"),
}

# Rows not in the manifest: (alias, relpath under the image root).
# RHEL needs a Red Hat login to download, so it lives only on the shared store.
EXTRA = [
    ("rhel8", "rhel/rhel-8.10-x86_64-kvm.qcow2"),
    ("rhel9", "rhel/rhel-9.7-x86_64-kvm.qcow2"),
    ("rhel10", "rhel/rhel-10.1-x86_64-kvm.qcow2"),
    ("ubuntu2404", "ubuntu/ubuntu-24.04-server-cloudimg-amd64.img"),
    ("debian13", "debian/debian-13-genericcloud-amd64.qcow2"),
]

# Aliases kept but commented out, with the reason.
DISABLED = {
    "debian12": "hangs at boot under libvirt, see issue #3",
}

HEADER = """\
# distro-matrix distro list. Generated by tools/gen-distros-tsv.py from the
# image-cache manifest; edit EXTRA/DISABLED there, not this file.
#
# alias            VM and lookup name. The runner looks for the image in the
#                  local cache first (<cache>/images/<alias>.qcow2), then at
#                  <image-root>/<qcow2_relpath>.
# family           rhel | debian | suse (package and init conventions).
# expected_os_id   the ID= value the runner asserts in the booted guest's
#                  /etc/os-release.
# qcow2_relpath    path under --image-root on the shared image store.
#
# Tabs separate fields; lines starting with # are ignored.
# alias\tfamily\texpected_os_id\tqcow2_relpath
"""


def lookup(alias: str) -> tuple[str, str]:
    for prefix in sorted(IDS, key=len, reverse=True):
        if alias.startswith(prefix):
            return IDS[prefix]
    raise SystemExit(f"gen-distros-tsv: no family/ID mapping for alias {alias!r}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--manifest",
        type=Path,
        default=Path.home() / ".cache/pqc-vm-matrix/manifest.tsv",
    )
    ap.add_argument("--output", type=Path, default=Path("distros.tsv"))
    args = ap.parse_args()

    rows: dict[str, str] = {}
    for line in args.manifest.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3:
            print(f"gen-distros-tsv: skipping malformed row: {line!r}", file=sys.stderr)
            continue
        alias, distro_dir, filename = fields[:3]
        rows[alias] = f"{distro_dir}/{filename}"
    for alias, relpath in EXTRA:
        rows.setdefault(alias, relpath)

    out = [HEADER.replace("\\t", "\t")]
    for alias in sorted(rows):
        family, os_id = lookup(alias)
        row = f"{alias}\t{family}\t{os_id}\t{rows[alias]}"
        if alias in DISABLED:
            out.append(f"# disabled: {DISABLED[alias]}\n# {row}\n")
        else:
            out.append(row + "\n")
    args.output.write_text("".join(out))
    print(f"gen-distros-tsv: wrote {len(rows)} distros to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
